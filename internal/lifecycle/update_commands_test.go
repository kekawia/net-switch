func TestUpdateSigningCommands(t *testing.T) {
	root := t.TempDir()
	path := func(name string) string { return filepath.Join(root, name) }
	run := func(args ...string) {
		t.Helper()
		if err := updateCommand(args); err != nil {
			t.Fatal(args[0], err)
		}
	}
	for _, name := range []string{"root", "release"} {
		run("update-keygen", "--key", path(name+".key"), "--public-key", path(name+".pub"))
	}
	original, err := os.ReadFile(path("root.key"))
	if err != nil {
		t.Fatal(err)
	}
	defer clear(original)
	if err := updateCommand([]string{"update-keygen", "--key", path("root.key"), "--public-key", path("other.pub")}); err == nil {
		t.Fatal("overwrote existing key")
	}
	after, _ := os.ReadFile(path("root.key"))
	if !bytes.Equal(original, after) {
		t.Fatal("existing key changed")
	}
	clear(after)
	if err := os.WriteFile(path("installer.exe"), []byte("signed update command fixture"), 0600); err != nil {
		t.Fatal(err)
	}
	keyExpiry := time.Now().Add(24 * time.Hour).UTC().Format(time.RFC3339)
	expiry := time.Now().Add(time.Hour).UTC().Format(time.RFC3339)
	run("update-issue-release-key", "--key", path("root.key"), "--public-key", path("release.pub"), "--out", path("key.json"), "--expires", keyExpiry)
	secret, err := os.ReadFile(path("release.key"))
	if err != nil {
		t.Fatal(err)
	}
	defer clear(secret)
	t.Setenv("NETSWITCH_TEST_RELEASE_KEY", string(secret))
	sign := []string{"update-sign-manifest", "--key-env", "NETSWITCH_TEST_RELEASE_KEY", "--root-public-key", path("root.pub"), "--key-statement", path("key.json"), "--installer", path("installer.exe"), "--version", "1.1.0", "--arch", "x64", "--expires", expiry, "--out", path("manifest.json")}
	run(sign...)
	verify := []string{"update-verify-manifest", "--root-public-key", path("root.pub"), "--key-statement", path("key.json"), "--manifest", path("manifest.json"), "--current", "1.0.0", "--arch", "x64", "--installer", path("installer.exe")}
	run(verify...)
	if err := updateCommand(sign); err == nil {
		t.Fatal("overwrote signed manifest")
	}
	if err := os.WriteFile(path("installer.exe"), []byte("modified update command fixture"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := updateCommand(verify); err == nil {
		t.Fatal("accepted tampered installer")
	}
	for _, input := range []struct{ path, env string }{{"", ""}, {path("release.key"), "NETSWITCH_TEST_RELEASE_KEY"}, {"", "NETSWITCH_TEST_MISSING_KEY"}} {
		if key, err := loadUpdateSigningSecret(input.path, input.env); err == nil {
			clear(key)
			t.Fatal("accepted ambiguous/missing key input")
		}
	}
	if err := updateCommand([]string{"update-issue-release-key", "--key-env", "NETSWITCH_TEST_RELEASE_KEY", "--out", path("forbidden.json")}); err == nil {
		t.Fatal("root issuance accepted online environment key")
	}
}

// Uses the independent official executable in both directions, not another
// fixture generated by our own signing implementation.
func TestUpdateSigningMinisignInteroperability(t *testing.T) {
	minisign, err := exec.LookPath("minisign")
	if err != nil {
		if os.Getenv("NETSWITCH_MINISIGN_REQUIRED") == "1" {
			t.Fatal("required official Minisign executable is missing")
		}
		t.Skip("official Minisign interoperability runs in Linux CI")
	}
	dir := t.TempDir()
	path := func(name string) string { return filepath.Join(dir, name) }
	runOfficial := func(args ...string) {
		t.Helper()
		command := exec.Command(minisign, args...)
		command.Dir = dir
		if out, err := command.CombinedOutput(); err != nil {
			t.Fatalf("minisign failed: %v: %s", err, out)
		}
	}
	run := func(args ...string) {
		t.Helper()
		if err := updateCommand(args); err != nil {
			t.Fatal(args[0], err)
		}
	}
	runOfficial("-G", "-W", "-s", path("official.key"), "-p", path("official.pub"))
	run("update-keygen", "--key", path("ours.key"), "--public-key", path("ours.pub"))
	for _, pair := range []struct{ root, release string }{{"ours", "official"}, {"official", "ours"}} {
		statement := path(pair.root + "-statement.json")
		run("update-issue-release-key", "--key", path(pair.root+".key"), "--public-key", path(pair.release+".pub"), "--out", statement, "--expires", time.Now().Add(time.Hour).UTC().Format(time.RFC3339))
		runOfficial("-V", "-m", statement, "-p", path(pair.root+".pub"))
		if err := os.Remove(statement + ".minisig"); err != nil {
			t.Fatal(err)
		}
		runOfficial("-S", "-m", statement, "-s", path(pair.root+".key"), "-t", "independent trusted comment")
		public, err := os.ReadFile(path(pair.root + ".pub"))
		if err != nil {
			t.Fatal(err)
		}
		raw, err := os.ReadFile(statement)
		if err != nil {
			t.Fatal(err)
		}
		signature, err := os.ReadFile(statement + ".minisig")
		if err != nil {
			t.Fatal(err)
		}
		if _, err := updates.VerifyReleaseKey(string(public), raw, signature, time.Now()); err != nil {
			t.Fatal("official signature rejected", err)
		}
		changed := []byte(strings.Replace(string(signature), "independent trusted comment", "untrusted changed comment", 1))
		if _, err := updates.VerifyReleaseKey(string(public), raw, changed, time.Now()); err == nil {
			t.Fatal("official trusted comment mutation accepted")
		}
	}
	t.Log("MINISIGN_INTEROP_PASS: both key formats, both signature directions, trusted-comment mutation")
}
